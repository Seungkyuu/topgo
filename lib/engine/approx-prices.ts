/** 모델명으로 시세를 찾는다: 겟챠 실가격 → 정규식 개략가 → fallback(그룹 기본가) 순. */
export function approxPrice(label: string, fallback: number): number {
  const real = REAL_PRICES[label];
  if (real !== undefined) return real;
  for (const [pattern, price] of RULES) {
    if (pattern.test(label)) return price;
  }
  return fallback;
}
